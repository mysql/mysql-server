void Pages_persistence::page_became_dirty(struct buf_block_t *buf_block) {
  buf_flush_insert_into_flush_list(buf_pool_from_block(buf_block), buf_block);
}

Pages_persistence::Lsn Pages_persistence::get_checkpoint_lsn() const {
  return log_checkpointing->get_checkpoint();
}

Pages_persistence::Status Pages_persistence::init() {
  buf_flush_list_added = Buf_flush_list_added_lsns::create();
  /* Even in read-only mode there could be flush job generated by
  intrinsic table operations. */
  buf_flush_page_cleaner_init();

  Log_checkpointing::init();

  if (const auto err = scan_tablespaces(); err != DB_SUCCESS) {
    ib::error(ER_IB_ERR_INNODB_PAGES_PERSISTENCE_FAILURE, __FUNCTION__,
              "scan_tablespaces()", (ulonglong)err);
    return Status::IO_ERROR;
  }

  return Status::SUCCESS;
}

Pages_persistence::Status Pages_persistence::assume_checkpoint_lsn(
    Lsn min_needed_lsn) {
  ut_a(log_sys == nullptr ||
       log_checkpointing->get_checkpoint() == min_needed_lsn);
  if (!log_checkpointing->save_checkpoint_value(min_needed_lsn)) {
    return Status::IO_ERROR;
  }
  buf_flush_list_added->assume_added_up_to(min_needed_lsn);
  return Status::SUCCESS;
}

void Pages_persistence::enable_checkpointing() {
  log_checkpointing->start_thread();
}

void Pages_persistence::enable_periodical_checkpoints() {
  log_checkpointing->enable_periodical_checkpoints();
}

void Pages_persistence::mtr_has_dirtied_pages(
    Lsn start_lsn, Lsn end_lsn, ::Flush_observer *observer,
    ut::Function_reference<void(ut::Function_reference<void(buf_block_t *)>)>
        iterate_over_dirty_pages) {
  const auto note_modification = [=](buf_block_t *block) {
    if (buf_page_get_state(&block->page) != BUF_BLOCK_MEMORY) {
      buf_flush_note_modification(block, start_lsn, end_lsn, observer);
    }
  };
  if (start_lsn != 0) {
    ut_a(observer == nullptr);
    ut_a(start_lsn < end_lsn);
    buf_flush_list_added->wait_to_add(start_lsn);

    DEBUG_SYNC_C("mtr_redo_before_add_dirty_blocks");

    iterate_over_dirty_pages(&note_modification);

    buf_flush_list_added->report_added(start_lsn, end_lsn);
  } else {
    ut_a(end_lsn == start_lsn);
    DEBUG_SYNC_C("mtr_noredo_before_add_dirty_blocks");

    iterate_over_dirty_pages(&note_modification);
  }
}

ut::Expected<std::vector<ib::fil::Tablespaces_nodes_interface::Tablespace_id>,
             Pages_persistence::Status>
Pages_persistence::recover_pages(Lsn &flushed_lsn) {
  using ib::redo::handler;

  /* We always try to do a recovery, even if the database had
  been shut down normally: this is the normal startup path */
  srv_recovery_crash(1);

  if (const auto open_status = handler->start_reading();
      open_status == ib::redo::Status::COULD_NOT_OPEN) {
    /* Following assert means that at this particular moment the log_sys is
    not running: even if it was for a moment, it got closed. */
    ut_a(log_sys == nullptr);

    /* ib::redo::Handler allows upgrade if log was logically empty, by
    removing old files. However the checkpoint_lsn found could be larger
    than flushed_lsn in the system tables space in case the shutdown wasn't
    slow. In such case we should start from an lsn at least equal to
    checkpoint_lsn as pages in the tablespace will have lsns larger than
    flushed_lsn. */
    if (recv_sys->checkpoint_lsn != 0) {
      ut_ad(flushed_lsn <= recv_sys->checkpoint_lsn);
      flushed_lsn = std::max(flushed_lsn, recv_sys->checkpoint_lsn);
    }

    /* When recreating files, we try not to reuse lsn which was already part
    of a block seen before shutdown. Files always start at a block boundary,
    so ib::redo::Handler::create(flushed_lsn) needs to set initial prefix
    of flushed_lsn % OS_FILE_LOG_BLOCK_SIZE bytes to something. Thus, in
    case of flushed_lsn % OS_FILE_LOG_BLOCK_SIZE > LOG_BLOCK_HDR_SIZE, it
    would have to fabricate mtr data, in some sense changing the history. To
    avoid this we move to the next block's header's end. This doesn't seem
    to be InnoDB's correctness requirement, as we probably wouldn't be able
    to read such fabricated mtr data anyway due to m_first_rec_group and
    checkpoint lsn being set to flushed_lsn as well. But we play safe, for
    example to avoid confusing backup tools which might try to operate on
    whole blocks. */
    flushed_lsn = ut_uint64_align_up(flushed_lsn, OS_FILE_LOG_BLOCK_SIZE) +
                  LOG_BLOCK_HDR_SIZE;

    if (const auto creation_status = handler->create(flushed_lsn);
        creation_status != ib::redo::Status::SUCCESS) {
      ib::error(ER_IB_ERR_INNODB_PAGES_PERSISTENCE_FAILURE, __FUNCTION__,
                "ib::redo::handler->create()", (ulonglong)creation_status);
      return ut::Unexpected(Status::IO_ERROR);
    }
    ut_ad(log_sys == nullptr ||
          log_checkpointing->get_checkpoint() == flushed_lsn);

    if (!log_checkpointing->save_checkpoint_value(flushed_lsn)) {
      ib::error(ER_IB_ERR_INNODB_PAGES_PERSISTENCE_FAILURE, __FUNCTION__,
                "log_checkpointing->save_checkpoint_value()",
                (ulonglong) false);
      return ut::Unexpected(Status::IO_ERROR);
    }

  } else if (open_status != ib::redo::Status::SUCCESS) {
    ib::error(ER_IB_ERR_INNODB_PAGES_PERSISTENCE_FAILURE, __FUNCTION__,
              "ib::redo::handler->start_reading()", (ulonglong)open_status);
    return ut::Unexpected(Status::IO_ERROR);
  }

  /* arch_init() needs log_sys object created by log_sys_create(), and is
  itself needed since recv_recovery_from_checkpoint_start() to track changes
  to pages. */
  if (handler->get_capabilities().supports_clone) {
    ut_a(log_sys != nullptr);
    arch_init();
  }

  if (const auto err = recv_recovery_from_checkpoint_start(flushed_lsn);
      err != DB_SUCCESS) {
    ib::error(ER_IB_ERR_INNODB_PAGES_PERSISTENCE_FAILURE, __FUNCTION__,
              "recv_recovery_from_checkpoint_start()", (ulonglong)err);
    return ut::Unexpected(Status::IO_ERROR);
  }

  if (handler->get_capabilities().supports_clone) {
    arch_page_sys->post_recovery_init();
  }

  ut_ad(clone_check_recovery_crashpoint(recv_sys->is_cloned_db));

  ut_a(srv_force_recovery < SRV_FORCE_NO_LOG_REDO || srv_read_only_mode);
  ut_a(!recv_sys->found_corrupt_log);

  if (srv_force_recovery < SRV_FORCE_NO_LOG_REDO) {
    srv_recovery_crash(2);

    /* Recovery complete, start verifying the page LSN on read. */
    recv_lsn_checks_on = true;
  }

  /* We have gone through the redo log, now check if all the
  tablespaces were found and recovered. */

  if (srv_force_recovery == 0 &&
      tablespace_scanning->check_missing_tablespaces()) {
    ib::error(ER_IB_MSG_1139);
    srv_recovery_crash(3);

    /* Set the abort flag to true. */
    auto p = recv_recovery_from_checkpoint_finish(true);

    ut_a(p == nullptr);

    return ut::Unexpected(Status::IO_ERROR);
  }

  /* We have successfully recovered from the redo log. The
  data dictionary should now be readable. */

  ut_a(!recv_sys->found_corrupt_log);

  if (!srv_force_recovery && !srv_read_only_mode) {
    ut_ad(buf_are_flush_lists_empty_validate());
    /* this is not really needed, as the buffer pool should be empty now */
    buf_flush_sync_all_buf_pools();
  }

  srv_recovery_crash(3);
  const auto recovered_lsn = recv_sys->recovered_lsn;

  m_dict_metadata = recv_recovery_from_checkpoint_finish(false);
  ut_a(m_dict_metadata != nullptr);

  buf_flush_list_added->assume_added_up_to(recovered_lsn);
  flushed_lsn = recovered_lsn;

  /* Return the list of tablespace ids discovered */
  std::vector<Tablespace_id> tablespace_ids;
  tablespace_scanning->get_found_space_ids(tablespace_ids);
  ut_a(!tablespace_ids.empty());
  return tablespace_ids;
}

Pages_persistence::Status Pages_persistence::recover_tables() {
  /* We need to save the dynamic metadata collected from redo log to DD
  buffer table here. This is to make sure that the dynamic metadata is not
  lost by any future checkpoint. Since DD and data dictionary in memory
  objects are not fully initialized at this point, the usual mechanism to
  persist dynamic metadata at checkpoint wouldn't work. */
  if (!recv_sys->is_cloned_db && !m_dict_metadata->empty()) {
    ut_a(!srv_read_only_mode);

    /* Open this table in case dict_metadata should be applied to this
    table before checkpoint. And because DD is not fully up yet, the table
    can be opened by internal APIs. */

    if (fil_space_t *space =
            fil_space_acquire_silent(dict_sys_t::s_dict_space_id);
        space == nullptr) {
      if (fil_ibd_open(true, FIL_TYPE_TABLESPACE, dict_sys_t::s_dict_space_id,
                       predefined_flags, dict_sys_t::s_dd_space_name,
                       dict_sys_t::s_dd_space_file_name, true,
                       false) != DB_SUCCESS) {
        ib::error(ER_IB_MSG_1142);
        return Status::IO_ERROR;
      }
    } else {
      fil_space_release(space);
    }

    dict_persist->table_buffer =
        ut::new_withkey<DDTableBuffer>(UT_NEW_THIS_FILE_PSI_KEY);
    /* We write redo log here. We assume that there should be enough room in
    log files, if log_free_check() works fine before crash. */
    m_dict_metadata->store();

    /* Flush logs to persist the changes. */
    ib::redo::must_persist_all(UT_LOCATION_HERE);
  }
  ut::delete_(m_dict_metadata);
  return Status::SUCCESS;
}

void Pages_persistence::persist_tablespace(Tablespace_id space_id,
                                           const trx_t *trx) {
  ut_a(trx == nullptr || trx->flush_observer == nullptr);
  buf_flush_pages(space_id, nullptr, trx);

  /* Ensure that all asynchronous IO is completed. */
  os_aio_wait_until_no_pending_writes();
  fil_flush(space_id);
}

void Pages_persistence::persist_tablespaces(::Flush_observer *observer) {
  const auto &trx = observer->get_trx();
  /* The flush observer is stored in the trx object and it happens to be the
  only one that the transaction is using, but it does not have to in general.
  This may be lifted in the future, especially if trx_t::flush_observer field is
  removed. */
  ut_a(observer == trx.flush_observer);

  buf_flush_pages(SPACE_UNKNOWN, observer, &trx);
}

