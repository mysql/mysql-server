class Pages_persistence_monitoring : public ib::Monitoring_interface {
  std::optional<mon_type_t> get_value(monitor_id_t id) override {
    switch (id) {
      case MONITOR_OVLD_LSN_BUF_DIRTY_PAGES_ADDED:
        return buf_flush_list_added->smallest_not_added_lsn();

      case MONITOR_OVLD_BUF_OLDEST_LSN_APPROX:
        return buf_pool_get_oldest_modification_approx();

      case MONITOR_OVLD_BUF_OLDEST_LSN_LWM:
        return buf_pool_get_oldest_modification_lwm();

      case MONITOR_OVLD_MAX_AGE_ASYNC:
        return log_checkpointing->adaptive_flush_min_age();

      case MONITOR_OVLD_MAX_AGE_SYNC:
        return log_checkpointing->adaptive_flush_max_age();

      default:
        /* As of now we do not expect InnoDB-specific counters not supported by
        InnoDB, hence the Debug assert. But in general the contract does not
        require the implementation to support all ids, so in Release mode we
        continue. */
#ifdef UNIV_DEBUG
        ut_error;
#else
        return std::nullopt;
#endif /* UNIV_DEBUG*/
    }
  }
};

ib::Monitoring_interface &Pages_persistence::get_monitoring() {
  static Pages_persistence_monitoring monitoring{};
  return monitoring;
}

dberr_t Pages_persistence::scan_tablespaces() {
  tablespace_scanning = ut::make_unique<Tablespace_scanning>();

  /* This is the default directory for IBD and IBU files. Put it first
  in the list of known directories. */
  tablespace_scanning->add_scan_dir(MySQL_datadir_path.path());

  /* Add --innodb-data-home-dir as a known location for IBD and IBU files
  if it is not already there. */
  ut_ad(srv_data_home != nullptr && *srv_data_home != '\0');
  tablespace_scanning->add_scan_dir(Fil_path::remove_quotes(srv_data_home));

  /* Add --innodb-directories as known locations for IBD and IBU files. */
  if (srv_innodb_directories != nullptr && *srv_innodb_directories != 0) {
    tablespace_scanning->add_scan_dirs(
        Fil_path::remove_quotes(srv_innodb_directories));
  }

  /* Note whether the undo path is different (not the same or under)
  from all other known directories. If so, this will allow us to keep
  IBD files out of this unique undo location.*/
  MySQL_undo_path_is_unique =
      !tablespace_scanning->is_known_path(MySQL_undo_path.path());

  /* For the purpose of file discovery at startup, we need to scan
  --innodb-undo-directory also if it is different from the locations above.
  NOTE : Avoid calling add_scan_dir if UNDO is non-unique becuase in that case
  it will be under datadir. And as datadir is already set to be scanned there
  will be warning emitted in server log. */
  if (MySQL_undo_path_is_unique) {
    tablespace_scanning->add_scan_dir(Fil_path::remove_quotes(MySQL_undo_path));
  }

  ib::info(ER_IB_MSG_378) << "Directories to scan '"
                          << tablespace_scanning->get_dirs() << "'";

  return tablespace_scanning->scan();
}

