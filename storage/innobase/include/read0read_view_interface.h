#pragma once

#include "trx0types.h"

struct table_name_t;

class Read_view_interface {
 public:
  virtual ~Read_view_interface() = default;

  /** Check whether the changes by id are visible.
  @param[in]    id      transaction id to check against the view
  @return whether the view sees the modifications of id. */
  [[nodiscard]] virtual bool changes_visible(trx_id_t id) const = 0;

  /** Checks if changes made by each trx with trx->id smaller or equal to id,
  should be visible to this read view.
  Conceptually equivalent to: forall x<=id . changes_visible(x).
  @param[in] id             max transaction id to check
  @return true if view sees all transactions with smaller or equal id */
  [[nodiscard]] virtual bool sees_all_trxs_with_id_smaller_or_equal_to(
      trx_id_t id) const = 0;

  /** This read view does not need Undo Logs generated by transactions with
  trx->no strictly smaller than this value.
  @return safe estimate of the lowest value of TRX_UNDO_TRX_NO header in Undo
  Logs still needed to support this read view */
  [[nodiscard]] virtual trx_id_t get_lowest_needed_trx_no() const = 0;

  /** Describe the read-view.
  @param[in] file           file to write to */
  virtual void print(FILE *file) const = 0;
};