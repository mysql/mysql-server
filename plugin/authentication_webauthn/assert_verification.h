#ifndef ASSERT_VERIFICATION_H
#define ASSERT_VERIFICATION_H

#include <fido.h>

namespace server_authentication {
/**
   Class to perform authentication(aka assertion in FIDO terminology) by
   verifying the signed signature sent by FIDO device.
*/
class assert_verification {
 public:
  assert_verification();
  virtual ~assert_verification();

  /**
     Helper methods to set:
      1. client data hash which consists of relying party ID and random salt.
      2. Authenticator data generated by FIDO device.
      3. Signature to be verified by the relying party using the public key.
      4. Relying party.
   */
  bool set_client_data(const unsigned char *cd, size_t len);
  bool set_authdata(const unsigned char *auth_data, size_t len,
                    size_t index = 0);
  bool set_signature(const unsigned char *sig, size_t len, size_t index = 0);
  bool set_rp_id(const char *rp);
  bool set_assertion_count(size_t count);

  /** Method to verify signature */
  bool verify_signature(int alg, const unsigned char *pk);

 private:
  /* An abstract type to hold information needed to do assertions. */
  fido_assert_t *m_assert;
};
}  // namespace server_authentication
#endif  // ASSERT_VERIFICATION_H
